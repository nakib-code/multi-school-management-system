const generateTemporaryPassword = (): string => {
	const upper = "ABCDEFGHJKLMNPQRSTUVWXYZ";
	const lower = "abcdefghjkmnpqrstuvwxyz";
	const digits = "23456789";
	const symbols = "@#$!";
	const all = upper + lower + digits + symbols;

	const chars = [
		upper[crypto.randomInt(upper.length)]!,
		lower[crypto.randomInt(lower.length)]!,
		digits[crypto.randomInt(digits.length)]!,
		symbols[crypto.randomInt(symbols.length)]!,
	];
	for (let i = 0; i < 6; i++) {
		chars.push(all[crypto.randomInt(all.length)]!);
	}
	// Shuffle deterministically with crypto randomness
	for (let i = chars.length - 1; i > 0; i--) {
		const j = crypto.randomInt(i + 1);
		[chars[i], chars[j]] = [chars[j]!, chars[i]!];
	}
	return chars.join("");
};

export const createTeacher = async (input: CreateTeacherInput) => {
	const {
		schoolId,
		name,
		email,
		password,
		employeeId,
		firstName,
		lastName,
		phone,
		address,
		dateOfBirth,
		joiningDate,
		designation,
		qualification,
	} = input;

	const normalizedEmail = email.trim().toLowerCase();
	const cleanPhone = phone?.trim() || undefined;

	const school = await prisma.school.findUnique({
		where: { id: schoolId },
		select: { id: true, status: true },
	});

	if (!school) {
		throw new AppError(404, "School not found");
	}

	if (school.status !== "ACTIVE") {
		throw new AppError(400, "Teacher cannot be created for an inactive school");
	}

	const existingUser = await prisma.user.findUnique({
		where: { email: normalizedEmail },
	});

	if (existingUser) {
		throw new AppError(409, "A user with this email already exists");
	}

	const existingTeacher = await prisma.teacher.findFirst({
		where: { schoolId, employeeId },
	});

	if (existingTeacher) {
		throw new AppError(409, "Employee ID already exists in this school");
	}

	// Optional password: auto-generate strong temporary password if omitted
	const isAutoGenerated = !password?.trim();
	const rawPassword = isAutoGenerated
		? generateTemporaryPassword()
		: password!.trim();
	const passwordHash = await bcrypt.hash(rawPassword, 12);

	const result = await prisma.$transaction(async (tx) => {
		const user = await tx.user.create({
			data: {
				name: name.trim(),
				email: normalizedEmail,
				...(cleanPhone ? { phone: cleanPhone } : {}),
				passwordHash,
				role: "TEACHER",
				status: "PENDING",
				mustChangePassword: isAutoGenerated,
				schoolId,
			},
			select: {
				id: true,
				name: true,
				email: true,
				phone: true,
				role: true,
				status: true,
				mustChangePassword: true,
				schoolId: true,
			},
		});

		const teacher = await tx.teacher.create({
			data: {
				userId: user.id,
				schoolId,
				employeeId: employeeId.trim(),
				firstName: firstName.trim(),
				...(lastName !== undefined ? { lastName: lastName.trim() } : {}),
				...(cleanPhone ? { phone: cleanPhone } : {}),
				...(address !== undefined ? { address: address.trim() } : {}),
				...(dateOfBirth !== undefined
					? { dateOfBirth: new Date(dateOfBirth) }
					: {}),
				...(joiningDate !== undefined
					? { joiningDate: new Date(joiningDate) }
					: {}),
				...(designation !== undefined
					? { designation: designation.trim() }
					: {}),
				...(qualification !== undefined
					? { qualification: qualification.trim() }
					: {}),
			},
			select: {
				id: true,
				employeeId: true,
				firstName: true,
				lastName: true,
				phone: true,
				address: true,
				dateOfBirth: true,
				joiningDate: true,
				designation: true,
				qualification: true,
				isActive: true,
			},
		});

		return { user, teacher };
	});

	const verificationCode = generateVerificationCode();

	await saveTeacherVerificationCode(
		schoolId,
		normalizedEmail,
		verificationCode,
	);

	try {
		await sendTeacherVerificationEmail(
			normalizedEmail,
			result.user.name,
			verificationCode,
		);
		await setTeacherOtpCooldown(schoolId, normalizedEmail, 60);
	} catch (error) {
		console.error("Failed to send teacher verification email:", error);

		await deleteTeacherVerificationCode(schoolId, normalizedEmail);

		await prisma.teacher.delete({ where: { id: result.teacher.id } });
		await prisma.user.delete({ where: { id: result.user.id } });

		throw new AppError(
			500,
			"Teacher account could not be created because verification email failed",
		);
	}

	return {
		id: result.teacher.id,
		employeeId: result.teacher.employeeId,
		firstName: result.teacher.firstName,
		lastName: result.teacher.lastName,
		phone: result.teacher.phone,
		email: result.user.email,
		role: result.user.role,
		status: result.user.status,
		mustChangePassword: result.user.mustChangePassword,
		emailVerified: false,
		...(isAutoGenerated ? { temporaryPassword: rawPassword } : {}),
	};
};

export const verifyTeacherEmail = async (
	schoolId: number,
	teacherId: number,
	code: string,
) => {
	const teacher = await prisma.teacher.findFirst({
		where: { id: teacherId, schoolId },
		select: {
			id: true,
			employeeId: true,
			userId: true,
			user: {
				select: {
					id: true,
					email: true,
					status: true,
					role: true,
					schoolId: true,
				},
			},
		},
	});

	if (!teacher) {
		throw new AppError(404, "Teacher not found");
	}

	if (teacher.user.status === "ACTIVE") {
		throw new AppError(400, "Teacher email is already verified");
	}

	if (teacher.user.status !== "PENDING") {
		throw new AppError(400, "Teacher account cannot be verified");
	}

	const verificationCode =
		(await getTeacherVerificationCode(schoolId, teacher.user.email)) ??
		(await getVerificationCode(teacher.user.email));

	if (!verificationCode) {
		throw new AppError(400, "Verification code has expired or does not exist");
	}

	if (verificationCode !== code) {
		throw new AppError(400, "Invalid verification code");
	}

	const updatedTeacher = await prisma.user.update({
		where: { id: teacher.userId },
		data: { status: "ACTIVE" },
		select: {
			id: true,
			name: true,
			email: true,
			role: true,
			status: true,
			schoolId: true,
		},
	});

	await Promise.all([
		deleteTeacherVerificationCode(schoolId, teacher.user.email),
		deleteVerificationCode(teacher.user.email),
	]);

	return {
		teacherId: teacher.id,
		employeeId: teacher.employeeId,
		email: updatedTeacher.email,
		emailVerified: true,
		status: updatedTeacher.status,
	};
};

export const resendTeacherOtp = async (schoolId: number, teacherId: number) => {
	const teacher = await prisma.teacher.findFirst({
		where: { id: teacherId, schoolId },
		select: {
			id: true,
			employeeId: true,
			user: {
				select: {
					id: true,
					name: true,
					email: true,
					status: true,
				},
			},
		},
	});

	if (!teacher) {
		throw new AppError(404, "Teacher not found");
	}

	if (teacher.user.status === "ACTIVE") {
		throw new AppError(400, "Teacher email is already verified");
	}

	if (teacher.user.status !== "PENDING") {
		throw new AppError(
			400,
			"OTP can only be resent for pending teacher accounts",
		);
	}

	const remainingSeconds = await getTeacherOtpCooldownRemaining(
		schoolId,
		teacher.user.email,
	);
	if (remainingSeconds > 0) {
		throw new AppError(
			429,
			`Please wait ${remainingSeconds} seconds before requesting another OTP`,
		);
	}

	const newCode = generateVerificationCode();
	await saveTeacherVerificationCode(schoolId, teacher.user.email, newCode);

	try {
		await sendTeacherVerificationEmail(
			teacher.user.email,
			teacher.user.name,
			newCode,
		);
		await setTeacherOtpCooldown(schoolId, teacher.user.email, 60);
	} catch (error) {
		console.error("Failed to resend teacher verification email:", error);
		throw new AppError(500, "Failed to resend verification email");
	}

	return {
		teacherId: teacher.id,
		email: teacher.user.email,
		expiresInSeconds: 600,
		cooldownSeconds: 60,
	};
};

export const resetTeacherPassword = async (
	schoolId: number,
	teacherId: number,
	input: ResetTeacherPasswordInput,
) => {
	const teacher = await prisma.teacher.findFirst({
		where: { id: teacherId, schoolId },
		select: {
			id: true,
			employeeId: true,
			userId: true,
			user: { select: { id: true, email: true, status: true } },
		},
	});

	if (!teacher) {
		throw new AppError(404, "Teacher not found");
	}

	const passwordHash = await bcrypt.hash(input.password, 12);

	await prisma.user.update({
		where: { id: teacher.userId },
		data: {
			passwordHash,
			mustChangePassword: input.mustChangePassword ?? true,
			passwordChangedAt: new Date(),
		},
	});

	return {
		teacherId: teacher.id,
		employeeId: teacher.employeeId,
		email: teacher.user.email,
		mustChangePassword: input.mustChangePassword ?? true,
	};
};

export const getTeachers = async (
	schoolId: number,
	params?: { search?: string },
) => {
	const search = params?.search?.trim();
	return prisma.teacher.findMany({
		where: {
			schoolId,
			...(search
				? {
						OR: [
							{ firstName: { contains: search, mode: "insensitive" } },
							{ lastName: { contains: search, mode: "insensitive" } },
							{ employeeId: { contains: search, mode: "insensitive" } },
							{ user: { email: { contains: search, mode: "insensitive" } } },
						],
					}
				: {}),
		},
		include: {
			user: {
				select: {
					id: true,
					name: true,
					email: true,
					phone: true,
					role: true,
					status: true,
				},
			},
		},
		orderBy: { createdAt: "desc" },
	});
};

